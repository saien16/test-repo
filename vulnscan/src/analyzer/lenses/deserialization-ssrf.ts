const SECTION = `## このレンズの観点: デシリアライズとリクエスト制御
外部由来の値が「どこへ繋ぐか」「何を復元するか」を決めていないかを見ます。

- **安全でないデシリアライズ (CWE-502)**
  外部由来のデータを、型やクラスを復元できる形式で読み戻しているケース。
  YAMLの任意タグ読み込み、pickle 相当、プロトタイプ汚染につながるマージ、
  関数やクラスを復元するリバイバ、node-serialize 系など。
  JSON.parse 自体は基本的に安全ですが、その後のマージ・代入で
  __proto__ / constructor を弾いているか（CWE-1321）は見てください。
- **SSRF (CWE-918)**
  外部由来の値が、サーバ側から発行するリクエストのURL・ホスト・ポートに入るケース。
  クラウドのメタデータエンドポイントや内部ネットワークへ到達しうるかが焦点です。
  許可リスト、スキーム制限、名前解決後のIP検証、リダイレクト追従の扱いを確認してください。
  ホスト部が固定でパスだけ外部由来なら、SSRFではなく別の問題として扱ってください。
- **XXE / 外部エンティティ展開 (CWE-611)**
  XMLパーサでDTD・外部エンティティを許可した状態で、外部由来の文書を解析しているケース。
  パーサ既定で無効なら問題ありません。SVG・XLSX・SOAPなどXMLを内包する形式も対象です。
- **オープンリダイレクト (CWE-601)**
  リダイレクト先が外部由来の値で決まるケース。相対パスに限定しているか、
  許可リストのホストかを確認してください。
- 併せて、外部由来のURLを取得して処理する経路での **ファイルスキーム利用**、
  **リクエストスマグリング / ヘッダインジェクション** につながる値の混入も対象です。

到達可能性（内部ネットワークやメタデータに実際に届くか）が判断の中心になるので、
そこが不明な場合は reasoning に前提として書き、confidence を下げてください。`;

