/** 暗号・シークレットレンズ: ハードコード秘密情報 / 弱い暗号 / 不適切な乱数 */

import { composeSystemPrompt } from './common.js';
import type { Lens } from './types.js';

const SECTION = `## このレンズの観点: 暗号とシークレット
秘密が秘密として扱われているか、暗号プリミティブの選択と使い方が妥当かを見ます。

- **ハードコードされた秘密情報 (CWE-798, CWE-259)**
  APIキー・パスワード・秘密鍵・トークン・接続文字列がコード中のリテラルにあるケース。
  テスト用のダミー値、公開鍵、サンプル、プレースホルダ（'changeme'、'xxx'、空文字）は
  区別してください。環境変数や秘密管理から読んでいるなら問題ありません。
  実在しそうな値かどうか（形式・長さ・エントロピー）を根拠に書いてください。
- **弱い・不適切な暗号アルゴリズム (CWE-327, CWE-328)**
  MD5 / SHA-1 をパスワード保存や署名検証に使う、DES / RC4 / ECBモード、
  パスワードの単純ハッシュ（ソルト・ストレッチング無し）、鍵長不足など。
  ファイルの同一性判定やキャッシュキー用途の MD5 は攻撃者が関与しない限り問題になりません。
- **不適切な乱数 (CWE-338, CWE-330)**
  トークン・セッションID・パスワードリセットキー・nonce・IV の生成に
  予測可能な乱数（Math.random、時刻シード、逐次カウンタ）を使っているケース。
  セキュリティ用途でない乱数（サンプリング、ジッタ、UI）は対象外です。
- **暗号の使い方の誤り**
  IV / nonce の再利用や固定値、CBCで完全性検証が無い、
  秘密比較が短絡評価（タイミング差）、証明書検証の無効化、
  鍵と暗号文を同じ場所に保存、など。

このレンズは「どこから来た値か」よりも「そのリテラル・その関数選択自体」が問題になるため、
dataFlow は短くなりがちです。その場合でも、値がどこで使われるか（sink）は書いてください。`;

export const cryptoSecretsLens: Lens = {
  id: 'crypto-secrets',
  title: '暗号・シークレット',
  systemPrompt: composeSystemPrompt(SECTION),
};
