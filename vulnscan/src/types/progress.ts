/**
 * 実行中のステージが報告する進捗。
 *
 * **単位を数値と一緒に運ぶ**のが要点。以前は表示側（cli/animation.ts）に
 * ステージ名→単位の対応表を置いていたが、何を数えているかは数えている側しか
 * 知らないので、表示側の推測は必ず古くなる（実際に②の単位は誤っていた）。
 *
 * この型を `core/` ではなく `types/` に置いてあるのは、各ステージが
 * オーケストレータへ依存せずに進捗を出せるようにするため
 * （依存の向きは types ← 各ステージ ← core）。
 */
export interface StageProgress {
  completed: number;
  total: number;
  /** 数えている対象の単位。「34/85 タスク」の「タスク」 */
  unit: string;
  /**
   * 同一ステージ内で母数が変わる局面の名前（②の 走査 / 自己検証 など）。
   * これが無いと、バーが100%まで行って別の母数で引き直されたときに
   * 「巻き戻った」ようにしか見えない。
   */
  phase?: string;
}

/**
 * 進捗を報告しないステージについて。
 *
 * ⑤構造把握・⑦編纂は、時間の大半が**LLM 1回の応答待ち**で、
 * その内側に観測できる段階が無い。⑥熱図描画は純粋な同期関数で一瞬終わる。
 * ここでバーを出すと、即座に100%になったまま数十秒固まることになり、
 * 「あと何割か」を偽って伝えてしまう。
 *
 * そのためこれらは進捗を出さず、`total === 0` のまま説明ラベルを表示する
 * （`cli/animation.ts` の `runningLine()` が分岐している）。
 * 無いより悪い進捗は出さない、という判断であって、配線し忘れではない。
 */
export const STAGES_WITHOUT_PROGRESS = ['architecture', 'heatmap', 'report'] as const;
